create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------
-- 1. Catálogos de dominio
-- ---------------------------------------------------------------------
create table public.roles (
  codigo       varchar(20)  primary key,
  nombre       varchar(60)  not null,
  descripcion  varchar(250)
);

create table public.estados_muestra (
  codigo       varchar(20)  primary key,
  nombre       varchar(60)  not null,
  orden        smallint     not null,
  descripcion  varchar(250)
);

-- ---------------------------------------------------------------------
-- 2. Usuarios
-- ---------------------------------------------------------------------
create table public.usuarios (
  id               bigint generated by default as identity primary key,
  username         varchar(30)   not null,
  nombre_completo  varchar(120)  not null,
  rol              varchar(20)   not null references public.roles (codigo),
  password_hash    char(64)      not null,                 -- SHA-256 hex (igual que la app)
  activo           boolean       not null default true,
  created_at       timestamptz   not null default now(),
  updated_at       timestamptz   not null default now(),
  constraint uq_usuarios_username unique (username)
);
create unique index ux_usuarios_username_upper on public.usuarios (upper(username));

-- ---------------------------------------------------------------------
-- 3. Centro -> Tren -> Línea
-- ---------------------------------------------------------------------
create table public.centros (
  id          bigint generated by default as identity primary key,
  nombre      varchar(100)  not null,
  codigo      varchar(30)   not null unique,
  activo      boolean       not null default true,
  created_at  timestamptz   not null default now()
);

create table public.trenes (
  id          bigint generated by default as identity primary key,
  centro_id   bigint        not null references public.centros (id),
  nombre      varchar(100)  not null,
  activo      boolean       not null default true,
  created_at  timestamptz   not null default now(),
  constraint uq_trenes_centro_nom unique (centro_id, nombre)
);

create table public.lineas (
  id          bigint generated by default as identity primary key,
  tren_id     bigint        not null references public.trenes (id),
  nombre      varchar(100)  not null,
  activo      boolean       not null default true,
  created_at  timestamptz   not null default now(),
  constraint uq_lineas_tren_nom unique (tren_id, nombre)
);

create index ix_trenes_centro on public.trenes (centro_id);
create index ix_lineas_tren   on public.lineas (tren_id);

-- ---------------------------------------------------------------------
-- 4. Muestras
-- ---------------------------------------------------------------------
create table public.muestras (
  id                     bigint generated by default as identity primary key,
  centro_id              bigint        not null references public.centros (id),
  tren_id                bigint        not null references public.trenes (id),
  linea_id               bigint        not null references public.lineas (id),
  fecha                  date          not null,
  hora                   varchar(5),                                   -- 'HH:MM'
  tramo_metros           numeric(6,3),
  operador_id            bigint        not null references public.usuarios (id),
  conteo_individuos      integer,
  observaciones          varchar(1000),
  calibre_promedio       numeric(6,2),
  calibre_min            numeric(6,2),
  calibre_max            numeric(6,2),
  peso_muestra           numeric(8,2),
  foto_url               varchar(500),
  estado                 varchar(20)   not null default 'borrador' references public.estados_muestra (codigo),
  comentario_supervisor  varchar(1000),
  supervisor_id          bigint        references public.usuarios (id),
  fecha_revision         timestamptz,
  densidad_ind_metro     numeric generated always as (
                           case when tramo_metros > 0 and conteo_individuos is not null
                                then round(conteo_individuos / tramo_metros, 2) end) stored,
  created_at             timestamptz   not null default now(),
  updated_at             timestamptz   not null default now(),
  constraint ck_muestras_hora     check (hora is null or hora ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  constraint ck_muestras_tramo    check (tramo_metros is null or tramo_metros > 0),
  constraint ck_muestras_conteo   check (conteo_individuos is null or conteo_individuos >= 0),
  constraint ck_muestras_peso     check (peso_muestra is null or peso_muestra >= 0),
  constraint ck_muestras_calibres check (calibre_min is null or calibre_max is null or calibre_min <= calibre_max),
  constraint ck_muestras_cal_prom check (calibre_promedio is null or calibre_min is null or calibre_max is null
                                         or calibre_promedio between calibre_min and calibre_max)
);

create index ix_muestras_centro_fecha on public.muestras (centro_id, fecha);
create index ix_muestras_linea_fecha  on public.muestras (linea_id, fecha);
create index ix_muestras_estado       on public.muestras (estado);
create index ix_muestras_operador     on public.muestras (operador_id);

-- ---------------------------------------------------------------------
-- 5. Historial de revisiones
-- ---------------------------------------------------------------------
create table public.revisiones_muestra (
  id               bigint generated by default as identity primary key,
  muestra_id       bigint        not null references public.muestras (id) on delete cascade,
  estado_anterior  varchar(20),
  estado_nuevo     varchar(20)   not null references public.estados_muestra (codigo),
  comentario       varchar(1000),
  usuario_id       bigint        references public.usuarios (id),
  fecha            timestamptz   not null default now()
);
create index ix_revisiones_muestra on public.revisiones_muestra (muestra_id, fecha);

-- ---------------------------------------------------------------------
-- 6. Triggers
-- ---------------------------------------------------------------------
create or replace function public.fn_muestras_validar()
returns trigger language plpgsql as $$
begin
  if not exists (select 1 from public.lineas where id = new.linea_id and tren_id = new.tren_id) then
    raise exception 'La línea no pertenece al tren indicado.';
  end if;
  if not exists (select 1 from public.trenes where id = new.tren_id and centro_id = new.centro_id) then
    raise exception 'El tren no pertenece al centro indicado.';
  end if;
  new.updated_at := now();
  return new;
end $$;

create trigger trg_muestras_validar
before insert or update on public.muestras
for each row execute function public.fn_muestras_validar();

create or replace function public.fn_muestras_historial()
returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' or old.estado is distinct from new.estado then
    insert into public.revisiones_muestra (muestra_id, estado_anterior, estado_nuevo, comentario, usuario_id)
    values (new.id,
            case when tg_op = 'INSERT' then null else old.estado end,
            new.estado,
            case when new.estado in ('observada','validada') then new.comentario_supervisor end,
            case when new.estado in ('observada','validada') then new.supervisor_id else new.operador_id end);
  end if;
  return new;
end $$;

create trigger trg_muestras_historial
after insert or update of estado on public.muestras
for each row execute function public.fn_muestras_historial();

create or replace function public.fn_set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger trg_usuarios_updated
before update on public.usuarios
for each row execute function public.fn_set_updated_at();

-- ---------------------------------------------------------------------
-- 7. Vistas (security_invoker: respetan RLS de quien consulta)
-- ---------------------------------------------------------------------
create or replace view public.v_usuarios with (security_invoker = true) as
select id, username, nombre_completo, rol, activo, created_at
from public.usuarios;

-- Sin security_invoker: se ejecuta con permisos del dueño para poder mostrar
-- nombres de operador/supervisor sin abrir la tabla usuarios (no expone hash).
create or replace view public.v_muestras_detalle as
select m.id,
       m.centro_id,  c.nombre as centro_nombre,
       m.tren_id,    t.nombre as tren_nombre,
       m.linea_id,   l.nombre as linea_nombre,
       m.fecha, m.hora, m.tramo_metros,
       m.operador_id, op.username as operador_username, op.nombre_completo as operador_nombre,
       m.conteo_individuos, m.densidad_ind_metro,
       m.observaciones, m.calibre_promedio, m.calibre_min, m.calibre_max, m.peso_muestra,
       m.foto_url, m.estado, m.comentario_supervisor,
       m.supervisor_id, sp.nombre_completo as supervisor_nombre,
       m.fecha_revision, m.created_at, m.updated_at
from public.muestras m
join public.centros  c  on c.id  = m.centro_id
join public.trenes   t  on t.id  = m.tren_id
join public.lineas   l  on l.id  = m.linea_id
join public.usuarios op on op.id = m.operador_id
left join public.usuarios sp on sp.id = m.supervisor_id;

create or replace view public.v_reporte_por_estado with (security_invoker = true) as
select e.codigo as estado, e.orden, count(m.id)::int as total
from public.estados_muestra e
left join public.muestras m on m.estado = e.codigo
group by e.codigo, e.orden;

create or replace view public.v_reporte_por_centro with (security_invoker = true) as
select c.nombre as centro, count(m.id)::int as total,
       round(avg(m.conteo_individuos), 1) as promedio_conteo,
       round(avg(m.densidad_ind_metro), 1) as promedio_densidad
from public.centros c
left join public.muestras m on m.centro_id = c.id
group by c.nombre;

create or replace view public.v_reporte_serie_temporal with (security_invoker = true) as
select to_char(m.fecha, 'YYYY-MM-DD') as fecha,
       coalesce(sum(m.conteo_individuos), 0)::int as total_individuos,
       count(*)::int as total_muestras
from public.muestras m
group by to_char(m.fecha, 'YYYY-MM-DD');

create or replace view public.v_historial_revisiones as
select r.id, r.muestra_id, r.estado_anterior, r.estado_nuevo, r.comentario,
       u.username as usuario, u.rol, r.fecha
from public.revisiones_muestra r
left join public.usuarios u on u.id = r.usuario_id;

-- ---------------------------------------------------------------------
-- 8. Funciones RPC (la app las llama con supabase.rpc / POST /rest/v1/rpc/...)
-- ---------------------------------------------------------------------

-- Login: recibe la contraseña en texto plano y compara con el hash SHA-256.
-- Devuelve el usuario sin password_hash, o nada si las credenciales fallan.
create or replace function public.fn_login(p_username text, p_password text)
returns table (id bigint, username varchar, nombre_completo varchar, rol varchar, activo boolean, created_at timestamptz)
language sql security definer set search_path = public as $$
  select u.id, u.username, u.nombre_completo, u.rol, u.activo, u.created_at
  from public.usuarios u
  where upper(u.username) = upper(trim(p_username))
    and u.activo
    and u.password_hash = encode(extensions.digest(p_password, 'sha256'), 'hex');
$$;

-- Crear usuario (pantalla Admin > Usuarios)
create or replace function public.fn_crear_usuario(p_username text, p_password text, p_nombre text, p_rol text)
returns bigint
language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  if length(coalesce(p_password, '')) < 4 then
    raise exception 'La contraseña debe tener al menos 4 caracteres.';
  end if;
  insert into public.usuarios (username, nombre_completo, rol, password_hash)
  values (trim(p_username), trim(p_nombre), p_rol,
          encode(extensions.digest(p_password, 'sha256'), 'hex'))
  returning id into v_id;
  return v_id;
end $$;

-- Actualizar usuario (nombre, rol, contraseña o estado activo)
create or replace function public.fn_actualizar_usuario(p_id bigint, p_nombre text default null,
                                                        p_rol text default null, p_password text default null,
                                                        p_activo boolean default null)
returns void
language plpgsql security definer set search_path = public as $$
begin
  update public.usuarios set
    nombre_completo = coalesce(trim(p_nombre), nombre_completo),
    rol             = coalesce(p_rol, rol),
    password_hash   = coalesce(encode(extensions.digest(p_password, 'sha256'), 'hex'), password_hash),
    activo          = coalesce(p_activo, activo)
  where id = p_id;
end $$;

-- ---------------------------------------------------------------------
-- 9. Row Level Security
--    MVP académico: la app usa su propio login (no Supabase Auth), por lo
--    que las políticas permiten operar con la anon key. La tabla usuarios
--    queda cerrada (solo vía RPC / vista sin hash).
--    Para producción: migrar a Supabase Auth y filtrar por auth.uid()/rol.
-- ---------------------------------------------------------------------
alter table public.roles              enable row level security;
alter table public.estados_muestra    enable row level security;
alter table public.usuarios           enable row level security;
alter table public.centros            enable row level security;
alter table public.trenes             enable row level security;
alter table public.lineas             enable row level security;
alter table public.muestras           enable row level security;
alter table public.revisiones_muestra enable row level security;

create policy "lectura roles"    on public.roles           for select to anon, authenticated using (true);
create policy "lectura estados"  on public.estados_muestra for select to anon, authenticated using (true);

create policy "catalogo centros" on public.centros for all to anon, authenticated using (true) with check (true);
create policy "catalogo trenes"  on public.trenes  for all to anon, authenticated using (true) with check (true);
create policy "catalogo lineas"  on public.lineas  for all to anon, authenticated using (true) with check (true);

create policy "muestras lectura"   on public.muestras for select to anon, authenticated using (true);
create policy "muestras insertar"  on public.muestras for insert to anon, authenticated with check (estado = 'borrador');
create policy "muestras modificar" on public.muestras for update to anon, authenticated using (true) with check (true);
create policy "muestras eliminar"  on public.muestras for delete to anon, authenticated using (estado = 'borrador');

create policy "historial lectura"  on public.revisiones_muestra for select to anon, authenticated using (true);
create policy "historial insertar" on public.revisiones_muestra for insert to anon, authenticated with check (true);

-- usuarios: sin políticas para anon => nadie lee password_hash directamente.
-- La vista v_usuarios (security_invoker) tampoco devolvería filas a anon,
-- por eso se expone una función de listado:
create or replace function public.fn_listar_usuarios()
returns setof public.v_usuarios
language sql security definer set search_path = public as $$
  select id, username, nombre_completo, rol, activo, created_at
  from public.usuarios order by nombre_completo;
$$;

grant execute on function public.fn_login(text, text)                                   to anon, authenticated;
grant execute on function public.fn_crear_usuario(text, text, text, text)               to anon, authenticated;
grant execute on function public.fn_actualizar_usuario(bigint, text, text, text, boolean) to anon, authenticated;
grant execute on function public.fn_listar_usuarios()                                   to anon, authenticated;

-- ---------------------------------------------------------------------
-- 10. Storage para fotos de muestras (bucket público de lectura)
-- ---------------------------------------------------------------------
do $$
begin
  if exists (select 1 from information_schema.schemata where schema_name = 'storage') then
    insert into storage.buckets (id, name, public)
    values ('fotos-muestras', 'fotos-muestras', true)
    on conflict (id) do nothing;

    execute $p$create policy "fotos subir" on storage.objects for insert to anon, authenticated
              with check (bucket_id = 'fotos-muestras')$p$;
    execute $p$create policy "fotos leer" on storage.objects for select to anon, authenticated
              using (bucket_id = 'fotos-muestras')$p$;
  end if;
end $$;
