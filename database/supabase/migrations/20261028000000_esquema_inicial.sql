-- =====================================================================
--  TrazaMar by NotFound - SUPABASE (PostgreSQL 15+)
--  Migración inicial: equivalente al esquema Oracle de database/oracle
--
--  Cómo aplicarla:
--   a) Supabase Dashboard -> SQL Editor -> pegar y ejecutar este archivo,
--      luego ejecutar ../seed.sql
--   b) Supabase CLI:  supabase link --project-ref <ref>  &&  supabase db push
--
--  Seguridad: RLS activado en todas las tablas. La app NO lee la tabla
--  usuarios directamente: el login y la gestión de cuentas pasan por
--  funciones RPC (SECURITY DEFINER) para no exponer password_hash.
