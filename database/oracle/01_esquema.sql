-- ---------------------------------------------------------------------
-- 1. Catálogos de dominio
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  codigo       VARCHAR2(20)  CONSTRAINT pk_roles PRIMARY KEY,
  nombre       VARCHAR2(60)  NOT NULL,
  descripcion  VARCHAR2(250)
);

COMMENT ON TABLE roles IS 'Perfiles de usuario del caso: operador, supervisor, analista, cliente, admin';

CREATE TABLE estados_muestra (
  codigo       VARCHAR2(20)  CONSTRAINT pk_estados_muestra PRIMARY KEY,
  nombre       VARCHAR2(60)  NOT NULL,
  orden        NUMBER(2)     NOT NULL,
  descripcion  VARCHAR2(250)
);

COMMENT ON TABLE estados_muestra IS 'Flujo de revisión: borrador -> pendiente -> observada -> corregida -> validada';

-- ---------------------------------------------------------------------
-- 2. Usuarios
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_usuarios PRIMARY KEY,
  username         VARCHAR2(30)   NOT NULL,
  nombre_completo  VARCHAR2(120)  NOT NULL,
  rol              VARCHAR2(20)   NOT NULL,
  password_hash    VARCHAR2(64)   NOT NULL,          -- SHA-256 hex (igual que la app)
  activo           NUMBER(1)      DEFAULT 1 NOT NULL,
  created_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_usuarios_username UNIQUE (username),
  CONSTRAINT fk_usuarios_rol      FOREIGN KEY (rol) REFERENCES roles (codigo),
  CONSTRAINT ck_usuarios_activo   CHECK (activo IN (0,1)),
  CONSTRAINT ck_usuarios_hash     CHECK (LENGTH(password_hash) = 64)
);

-- Login sin distinguir mayúsculas (la app usa COLLATE NOCASE)
CREATE UNIQUE INDEX ux_usuarios_username_upper ON usuarios (UPPER(username));

-- ---------------------------------------------------------------------
-- 3. Jerarquía de cultivo: Centro -> Tren -> Línea
-- ---------------------------------------------------------------------
CREATE TABLE centros (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_centros PRIMARY KEY,
  nombre      VARCHAR2(100)  NOT NULL,
  codigo      VARCHAR2(30)   NOT NULL,
  activo      NUMBER(1)      DEFAULT 1 NOT NULL,
  created_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_centros_codigo  UNIQUE (codigo),
  CONSTRAINT ck_centros_activo  CHECK (activo IN (0,1))
);

CREATE TABLE trenes (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_trenes PRIMARY KEY,
  centro_id   NUMBER         NOT NULL,
  nombre      VARCHAR2(100)  NOT NULL,
  activo      NUMBER(1)      DEFAULT 1 NOT NULL,
  created_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_trenes_centro      FOREIGN KEY (centro_id) REFERENCES centros (id),
  CONSTRAINT uq_trenes_centro_nom  UNIQUE (centro_id, nombre),
  CONSTRAINT ck_trenes_activo      CHECK (activo IN (0,1))
);

CREATE TABLE lineas (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_lineas PRIMARY KEY,
  tren_id     NUMBER         NOT NULL,
  nombre      VARCHAR2(100)  NOT NULL,
  activo      NUMBER(1)      DEFAULT 1 NOT NULL,
  created_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_lineas_tren       FOREIGN KEY (tren_id) REFERENCES trenes (id),
  CONSTRAINT uq_lineas_tren_nom   UNIQUE (tren_id, nombre),
  CONSTRAINT ck_lineas_activo     CHECK (activo IN (0,1))
);

CREATE INDEX ix_trenes_centro ON trenes (centro_id);
CREATE INDEX ix_lineas_tren   ON lineas (tren_id);

-- ---------------------------------------------------------------------
-- 4. Muestras (registro de terreno)
--    centro_id y tren_id se guardan junto a linea_id para consultar
--    rápido por centro/tren (igual que MuestraDto). Un trigger valida
--    que la línea pertenezca al tren y el tren al centro.
-- ---------------------------------------------------------------------
CREATE TABLE muestras (
  id                     NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_muestras PRIMARY KEY,
  centro_id              NUMBER         NOT NULL,
  tren_id                NUMBER         NOT NULL,
  linea_id               NUMBER         NOT NULL,
  fecha                  DATE           NOT NULL,
  hora                   VARCHAR2(5),                       -- 'HH24:MI'
  tramo_metros           NUMBER(6,3),
  operador_id            NUMBER         NOT NULL,
  conteo_individuos      NUMBER(8),
  observaciones          VARCHAR2(1000),
  calibre_promedio       NUMBER(6,2),                       -- mm
  calibre_min            NUMBER(6,2),
  calibre_max            NUMBER(6,2),
  peso_muestra           NUMBER(8,2),                       -- g
  foto_url               VARCHAR2(500),
  estado                 VARCHAR2(20)   DEFAULT 'borrador' NOT NULL,
  comentario_supervisor  VARCHAR2(1000),
  supervisor_id          NUMBER,
  fecha_revision         TIMESTAMP,
  -- densidad = individuos por metro (Reglas.densidad)
  densidad_ind_metro     NUMBER GENERATED ALWAYS AS (
                           CASE WHEN tramo_metros > 0 AND conteo_individuos IS NOT NULL
                                THEN ROUND(conteo_individuos / tramo_metros, 2) END) VIRTUAL,
  created_at             TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at             TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_muestras_centro     FOREIGN KEY (centro_id)     REFERENCES centros (id),
  CONSTRAINT fk_muestras_tren       FOREIGN KEY (tren_id)       REFERENCES trenes (id),
  CONSTRAINT fk_muestras_linea      FOREIGN KEY (linea_id)      REFERENCES lineas (id),
  CONSTRAINT fk_muestras_operador   FOREIGN KEY (operador_id)   REFERENCES usuarios (id),
  CONSTRAINT fk_muestras_supervisor FOREIGN KEY (supervisor_id) REFERENCES usuarios (id),
  CONSTRAINT fk_muestras_estado     FOREIGN KEY (estado)        REFERENCES estados_muestra (codigo),
  CONSTRAINT ck_muestras_hora       CHECK (hora IS NULL OR REGEXP_LIKE(hora, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
  CONSTRAINT ck_muestras_tramo      CHECK (tramo_metros IS NULL OR tramo_metros > 0),
  CONSTRAINT ck_muestras_conteo     CHECK (conteo_individuos IS NULL OR conteo_individuos >= 0),
  CONSTRAINT ck_muestras_peso       CHECK (peso_muestra IS NULL OR peso_muestra >= 0),
  CONSTRAINT ck_muestras_calibres   CHECK (calibre_min IS NULL OR calibre_max IS NULL OR calibre_min <= calibre_max),
  CONSTRAINT ck_muestras_cal_prom   CHECK (calibre_promedio IS NULL OR calibre_min IS NULL OR calibre_max IS NULL
                                           OR calibre_promedio BETWEEN calibre_min AND calibre_max)
);

CREATE INDEX ix_muestras_centro_fecha ON muestras (centro_id, fecha);
CREATE INDEX ix_muestras_linea_fecha  ON muestras (linea_id, fecha);
CREATE INDEX ix_muestras_estado       ON muestras (estado);
CREATE INDEX ix_muestras_operador     ON muestras (operador_id);

-- ---------------------------------------------------------------------
-- 5. Historial de revisiones (trazabilidad de cada cambio de estado)
-- ---------------------------------------------------------------------
CREATE TABLE revisiones_muestra (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_revisiones PRIMARY KEY,
  muestra_id       NUMBER        NOT NULL,
  estado_anterior  VARCHAR2(20),
  estado_nuevo     VARCHAR2(20)  NOT NULL,
  comentario       VARCHAR2(1000),
  usuario_id       NUMBER,
  fecha            TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_revisiones_muestra FOREIGN KEY (muestra_id) REFERENCES muestras (id) ON DELETE CASCADE,
  CONSTRAINT fk_revisiones_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
  CONSTRAINT fk_revisiones_estado  FOREIGN KEY (estado_nuevo) REFERENCES estados_muestra (codigo)
);

CREATE INDEX ix_revisiones_muestra ON revisiones_muestra (muestra_id, fecha);

