-- 6.1 Coherencia centro/tren/línea + updated_at
CREATE OR REPLACE TRIGGER trg_muestras_bi_bu
BEFORE INSERT OR UPDATE ON muestras
FOR EACH ROW
DECLARE
  v_tren_id   NUMBER;
  v_centro_id NUMBER;
BEGIN
  SELECT tren_id INTO v_tren_id FROM lineas WHERE id = :NEW.linea_id;
  IF v_tren_id <> :NEW.tren_id THEN
    RAISE_APPLICATION_ERROR(-20001, 'La línea no pertenece al tren indicado.');
  END IF;

  SELECT centro_id INTO v_centro_id FROM trenes WHERE id = :NEW.tren_id;
  IF v_centro_id <> :NEW.centro_id THEN
    RAISE_APPLICATION_ERROR(-20002, 'El tren no pertenece al centro indicado.');
  END IF;

  :NEW.updated_at := SYSTIMESTAMP;
END;
/

-- 6.2 Registro automático del historial cuando cambia el estado
CREATE OR REPLACE TRIGGER trg_muestras_historial
AFTER INSERT OR UPDATE OF estado ON muestras
FOR EACH ROW
DECLARE
  v_anterior   VARCHAR2(20);
  v_comentario VARCHAR2(1000);
  v_usuario    NUMBER;
BEGIN
  IF INSERTING OR NVL(:OLD.estado, '-') <> :NEW.estado THEN
    IF INSERTING THEN
      v_anterior := NULL;
    ELSE
      v_anterior := :OLD.estado;
    END IF;

    IF :NEW.estado IN ('observada', 'validada') THEN
      v_comentario := :NEW.comentario_supervisor;
      v_usuario    := :NEW.supervisor_id;
    ELSE
      v_comentario := NULL;
      v_usuario    := :NEW.operador_id;
    END IF;

    INSERT INTO revisiones_muestra (muestra_id, estado_anterior, estado_nuevo, comentario, usuario_id)
    VALUES (:NEW.id, v_anterior, :NEW.estado, v_comentario, v_usuario);
  END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_usuarios_bu
BEFORE UPDATE ON usuarios
FOR EACH ROW
BEGIN
  :NEW.updated_at := SYSTIMESTAMP;
END;
